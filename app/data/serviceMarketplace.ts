export const marketplaceCategories = Array.from(
  new Set(marketplaceServices.map((service) => service.marketplaceCategory)),
).sort();

export function getMarketplaceService(slug: string) {
  return marketplaceServices.find((service) => service.slug === slug);
}

export function getMarketplaceServicesByStudio(studioId: Studio["id"]) {
  return marketplaceServices.filter((service) => service.studioId === studioId);
}

import type { Studio } from "./studios";

export type EngagementModel = "sprint" | "project" | "ongoing";

export type MarketplaceService = {
  slug: string;
  title: string;
  shortTitle: string;
  studioId: Studio["id"];
  marketplaceCategory: string;
  summary: string;
  outcome: string;
  idealFor: string[];
  deliverables: string[];
  specialistRoles: string[];
  process: string[];
  engagements: EngagementModel[];
  searchTerms: string[];
  featured?: boolean;
};

export const engagementModels: Record<EngagementModel, { title: string; description: string }> = {
  sprint: {
    title: "Clarity sprint",
    description: "A focused discovery engagement that turns an uncertain request into a decision-ready scope.",
  },
  project: {
    title: "Defined project",
    description: "A written scope with agreed deliverables, milestones, responsibilities, review points, and handover.",
  },
  ongoing: {
    title: "Ongoing partnership",
    description: "Recurring specialist capacity for improvement, production, maintenance, or operational support.",
  },
};

const studioDefaults: Record<
  Studio["id"],
  { specialistRoles: string[]; process: string[] }
> = {
  technology: {
    specialistRoles: ["Product strategist", "Experience designer", "Technical specialist"],
    process: ["Discover", "Architect", "Build", "Validate", "Launch"],
  },
  creative: {
    specialistRoles: ["Creative strategist", "Visual designer", "Production specialist"],
    process: ["Audit", "Direct", "Design", "Refine", "Handover"],
  },
  growth: {
    specialistRoles: ["Growth strategist", "Channel specialist", "Measurement lead"],
    process: ["Diagnose", "Plan", "Produce", "Launch", "Optimize"],
  },
  video: {
    specialistRoles: ["Creative producer", "Editor or animator", "Delivery specialist"],
    process: ["Concept", "Prepare", "Produce", "Review", "Deliver"],
  },
  support: {
    specialistRoles: ["Operations lead", "Domain specialist", "Quality reviewer"],
    process: ["Clarify", "Set up", "Execute", "Review", "Improve"],
  },
};

function defineService(
  input: Omit<MarketplaceService, "specialistRoles" | "process" | "engagements"> &
    Partial<Pick<MarketplaceService, "specialistRoles" | "process" | "engagements">>,
): MarketplaceService {
  const defaults = studioDefaults[input.studioId];
  return {
    ...input,
    specialistRoles: input.specialistRoles ?? defaults.specialistRoles,
    process: input.process ?? defaults.process,
    engagements: input.engagements ?? ["sprint", "project", "ongoing"],
  };
}

